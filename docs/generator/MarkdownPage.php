<?php

declare(strict_types=1);

namespace Stewart\Docs\Generator;

final readonly class MarkdownPage
{
    public function __construct(
        public string $title,
        public string $description,
        public int $sidebarOrder,
        public string $body,
    ) {}

    public function renderMarkdown(): string
    {
        return implode("\n", [
            '---',
            'title: ' . $this->title,
            'description: ' . $this->description,
            'sidebar:',
            '  order: ' . $this->sidebarOrder,
            '---',
            '',
            '<!-- Generated by `make docs-reference` from the code; edit the generator in docs/generator/, not this file. -->',
            '',
            rtrim($this->body),
            '',
        ]);
    }
}
