<?php

declare(strict_types=1);

namespace Stewart\PHPStan\Rule;

use PhpParser\Node;
use PHPStan\Analyser\Scope;
use PHPStan\Node\CollectedDataNode;
use PHPStan\Rules\Rule;
use PHPStan\Rules\RuleErrorBuilder;
use Stewart\PHPStan\Collector\GeneratedCodeFromOlderMajorCollector;

// Reported once per run, on the first analysed file, since the generated classes are usually not analysed.
/** @implements Rule<CollectedDataNode> */
final readonly class GeneratedCodeFromOlderMajorRule implements Rule
{
    private const string IDENTIFIER = 'stewart.generatedCode';

    public function getNodeType(): string
    {
        return CollectedDataNode::class;
    }

    public function processNode(Node $node, Scope $scope): array
    {
        $collected = $node->get(GeneratedCodeFromOlderMajorCollector::class);

        if ($collected === []) {
            return [];
        }

        ksort($collected);
        $file = (string) array_key_first($collected);

        return [
            RuleErrorBuilder::message(\sprintf('%s was generated by Stewart 1.x, so entity IDs and action names go unchecked.', $collected[$file][0]))
                ->identifier(self::IDENTIFIER)
                ->tip('Run `make generate`.')
                ->file($file)
                ->line(1)
                ->build(),
        ];
    }
}
