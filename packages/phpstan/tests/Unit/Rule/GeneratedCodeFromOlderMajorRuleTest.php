<?php

declare(strict_types=1);

namespace Stewart\PHPStan\Tests\Unit\Rule;

use PHPStan\Rules\Rule;
use PHPStan\Testing\RuleTestCase;
use PHPUnit\Framework\Attributes\CoversClass;
use Stewart\PHPStan\Cache\ManifestResultCacheValue;
use Stewart\PHPStan\Collector\GeneratedCodeFromOlderMajorCollector;
use Stewart\PHPStan\Manifest\ManifestCatalogLoader;
use Stewart\PHPStan\Rule\GeneratedCodeFromOlderMajorRule;

/** @extends RuleTestCase<GeneratedCodeFromOlderMajorRule> */
#[CoversClass(GeneratedCodeFromOlderMajorRule::class)]
#[CoversClass(GeneratedCodeFromOlderMajorCollector::class)]
#[CoversClass(ManifestCatalogLoader::class)]
#[CoversClass(ManifestResultCacheValue::class)]
final class GeneratedCodeFromOlderMajorRuleTest extends RuleTestCase
{
    private const string MESSAGE = 'Stewart\PHPStan\Tests\Fixtures\OlderMajor was generated by Stewart 1.x, so entity IDs and action names go unchecked.';

    public function testATreeFromOlderMajorIsReportedOncePerRun(): void
    {
        $this->analyse(
            [__DIR__ . '/../../Fixtures/Analysed/OlderMajorCalls.php', __DIR__ . '/../../Fixtures/Analysed/ActionCalls.php'],
            [[self::MESSAGE, 1, 'Run `make generate`.']],
        );
    }

    public function testTheResultCacheTellsATreeFromOlderMajorApart(): void
    {
        self::assertSame('older-major', self::getContainer()->getByType(ManifestResultCacheValue::class)->getValue(ManifestResultCacheValue::MANIFEST_KEY));
    }

    public static function getAdditionalConfigFiles(): array
    {
        return [__DIR__ . '/../../Fixtures/extension-older-major.neon'];
    }

    protected function getRule(): Rule
    {
        return self::getContainer()->getByType(GeneratedCodeFromOlderMajorRule::class);
    }

    protected function getCollectors(): array
    {
        return [self::getContainer()->getByType(GeneratedCodeFromOlderMajorCollector::class)];
    }
}
